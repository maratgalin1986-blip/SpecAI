// Russian cities the platform recognises in free text (chat orders, addresses,
// base addresses) and places on the map: every city with about 100 000 people
// or more, the regional capitals below that, and the towns of Tatarstan where
// СпецПласт16's own fleet works. One data row per city; the case forms
// («в Казани», «из Екатеринбурга», «по Челнам», «под Самарой») are generated
// from the name by `cityForms`, so a new city is one line.

export interface RussianCity {
  /** The name as Nominatim and people write it: «Набережные Челны». */
  name: string;
  /** The centre, for distances when only the city of an order is known. */
  lat: number;
  lon: number;
  /** The federal subject: «Республика Татарстан». */
  region: string;
}

