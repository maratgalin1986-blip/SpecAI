function fold(text: string): string {
  return text.toLowerCase().replace(/ё/g, 'е');
}

/** The case forms of one word of a name («челны» → челны, челнов, челнам, челнах…). */
function wordForms(word: string, role: 'noun' | 'adjective'): string[] {
  const stem = (cut: number) => word.slice(0, word.length - cut);
  const with_ = (cut: number, endings: string[]) => endings.map((ending) => stem(cut) + ending);
  if (role === 'adjective') {
    if (/(?:ий|ый)$/.test(word)) {
      return with_(2, ['ий', 'ый', 'ого', 'его', 'ому', 'ему', 'им', 'ым', 'ом', 'ем']);
    }
    if (/(?:ые|ие)$/.test(word))
      return with_(2, ['ые', 'ие', 'ых', 'их', 'ым', 'им', 'ыми', 'ими']);
    if (/(?:ое|ее)$/.test(word))
      return with_(2, ['ое', 'ее', 'ого', 'его', 'ому', 'ему', 'ым', 'ом']);
    // «Сергиев Посад»: a possessive adjective declines like a noun.
  }
  if (word.endsWith('ь')) return with_(1, ['ь', 'и', 'ью', 'я', 'ю', 'ем', 'е']);
  if (word.endsWith('й')) return with_(1, ['й', 'я', 'ю', 'ем', 'е']);
  if (word.endsWith('а')) return with_(1, ['а', 'ы', 'и', 'е', 'у', 'ой', 'ою']);
  if (word.endsWith('я')) return with_(1, ['я', 'и', 'е', 'ю', 'ей']);
  if (word.endsWith('о')) return with_(1, ['о', 'а', 'у', 'ом', 'е']);
  // Plural names: «Челны» → «из Челнов», «Чебоксары» → «из Чебоксар».
  if (/[ыи]$/.test(word)) return with_(1, ['ы', 'и', 'ов', 'ев', 'ам', 'ах', 'ами', '']);
  return with_(0, ['', 'а', 'у', 'ом', 'ем', 'е', 'ым']);
}

function isAdjective(word: string): boolean {
  return /(?:ий|ый|ые|ие|ое|ее)$/.test(word);
}

/**
 * Every spelling of a city name the text matcher accepts, lower-case with
 * «ё» as «е»: the case forms, plus the extra forms and short names of its row.
 */
export function cityForms(name: string): string[] {
  const row = ROWS.find((item) => item[0] === name);
  const flags = (row?.[4] ?? '').split(/\s+/).filter(Boolean);
  const folded = fold(name);
  const forms = new Set<string>();
  if (flags.includes('=')) {
    forms.add(folded);
  } else if (folded.includes('-на-')) {
    // «Ростов-на-Дону»: only the first part declines.
    const at = folded.indexOf('-');
    const tail = folded.slice(at + 1);
    for (const form of wordForms(folded.slice(0, at), 'noun')) forms.add(`${form}-${tail}`);
  } else {
    // Words are joined by a space or a hyphen; the last word always declines,
    // the others when they are adjectives («Нижнего Новгорода», «Петропавловска-
    // Камчатского») or the pair is a noun pair («Орехово-Зуево»).
    const parts = folded.split(/([ -])/);
    const words = parts.filter((_, index) => index % 2 === 0);
    const joints = parts.filter((_, index) => index % 2 === 1);
    const last = words.length - 1;
    const optionsOf = (word: string, index: number): string[] => {
      if (index === last) return wordForms(word, isAdjective(word) ? 'adjective' : 'noun');
      if (isAdjective(word)) return wordForms(word, 'adjective');
      // «Ханты-Мансийск», «Санкт-Петербург», «Йошкар-Ола»: the first part stays,
      // unless the last part is an adjective («Каменск-Уральский»), the pair is
      // a noun pair («Орехово-Зуево») or a possessive («Сергиева Посада»).
      if (isAdjective(words[last] ?? '') || /(?:о|ев|ов)$/.test(word)) {
        return [word, ...wordForms(word, 'noun')];
      }
      return [word];
    };
    let combos = [''];
    words.forEach((word, index) => {
      const options = optionsOf(word, index);
      combos = combos.flatMap((prefix) =>
        options.map((option) => (index === 0 ? option : `${prefix}${joints[index - 1]}${option}`)),
      );
    });
    for (const combo of combos) forms.add(combo);
  }
  for (const extra of flags) {
    if (extra === '?' || extra === '=') continue;
    // A short name declines too («челны» → «в Челнах»); an abbreviation does not.
    if (extra.length <= 3) forms.add(extra);
    else for (const form of wordForms(extra, 'noun')) forms.add(form);
  }
  forms.delete('');
  return [...forms];
}

const LETTER = '[a-zа-я0-9]';
// «ул. Кирова», «проспект Победы, Пушкина 3»: a street named after a person or
// a city is not the place of the order.
const STREET_BEFORE =
  /(?:^|[^a-zа-я])(?:ул|улица|улице|улицы|пр|просп|проспект|проспекте|пр-т|пер|переулок|переулке|бульвар|бульваре|б-р|бул|шоссе|ш|пл|площадь|площади|наб|набережная|набережной|тракт|тракте|проезд|проезде|мкр|микрорайон|им|имени)\.?\s*$/;
// An ambiguous name counts only as a place: «в Кирове», «из Шахт», «г. Артём».
const PLACE_BEFORE =
  /(?:^|[^a-zа-я])(?:в|во|из|по|под|до|около|возле|рядом с|г|гор|город|города|городе|городу|р-н|район)\.?\s*$/;

interface Matcher {
  city: RussianCity;
  pattern: RegExp;
  ambiguous: boolean;
}

let matchers: Matcher[] | null = null;

function escape(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\-]/g, '\\$&');
}

function cityMatchers(): Matcher[] {
  matchers ??= ROWS.map((row, index) => {
    // Longest forms first, so «челнами» is not cut to «челна».
    const forms = cityForms(row[0]).sort((a, b) => b.length - a.length);
    return {
      city: RUSSIAN_CITIES[index] as RussianCity,
      pattern: new RegExp(`(?<!${LETTER}|-)(?:${forms.map(escape).join('|')})(?!${LETTER})`, 'g'),
      ambiguous: (row[4] ?? '').split(/\s+/).includes('?'),
    };
  });
  return matchers;
}

/**
 * The earliest known city named in a free text and where it starts: «нужен
 * кран в Казани» → Казань. Streets named after a city or a person («ул.
 * Кирова», «Нижнекамское шоссе») do not count, and names that are also
 * ordinary words count only as a place: after «в», «из», «г.» … («в Кирове»,
 * «г. Шахты»), or — with `address: true`, for an address or a stored city —
 * as a whole comma part («Киров, ул. Ленина 5», «Киров»). In a chat message a
 * name before a comma is more often a person («Артём, привет»).
 */
export function findCityInText(
  text: string | null | undefined,
  options: { address?: boolean } = {},
): { city: RussianCity; index: number } | null {
  if (!text) return null;
  // Same length as the text, so indexes point into the original.
  const lower = fold(text);
  let best: { city: RussianCity; index: number; length: number } | null = null;
  for (const { city, pattern, ambiguous } of cityMatchers()) {
    pattern.lastIndex = 0;
    for (const match of lower.matchAll(pattern)) {
      const index = match.index ?? 0;
      if (best && index > best.index) break;
      const length = match[0].length;
      // Only the end of it is tested (the patterns end with `$`).
      const before = lower.slice(0, index);
      if (STREET_BEFORE.test(before)) continue;
      if (ambiguous) {
        const first = text.charAt(index);
        if (first === first.toLowerCase()) continue;
        const wholePart =
          options.address === true &&
          /(?:^|,)\s*$/.test(before) &&
          /^\s*(?:,|$)/.test(lower.slice(index + length));
        if (!wholePart && !PLACE_BEFORE.test(before)) continue;
      }
      if (!best || index < best.index || (index === best.index && length > best.length)) {
        best = { city, index, length };
      }
      break;
    }
  }
  return best ? { city: best.city, index: best.index } : null;
}

/** The known city with exactly this name (any case, «ё» or «е»), else null. */
export function cityByName(name: string | null | undefined): RussianCity | null {
  const key = fold(name?.trim() ?? '').replace(/\s+/g, ' ');
  if (!key) return null;
  return RUSSIAN_CITIES.find((city) => fold(city.name) === key) ?? null;
}
