// Что предлагать фирме по её сфере (владелец, 2026-11-12: «изучать каждую компанию и предлагать ей
// именно то, чем она занимается, без воды»). Для каждой ниши офиса — только те решения, которые
// нужны такому бизнесу, названные его словами: автосервису — запись на ремонт и заказ-наряды, а не
// «CRM вообще»; юристу камеры не предлагаем. Из этого строятся абзац письма и сцены презентации
// (/pokaz/<token>). Тексты без цен, сроков и обещаний результата (К6); новые ниши без своей
// записи получают общий набор из двух сцен.

export type PitchSceneKind = 'site' | 'crm' | 'app' | 'camera';

export interface PitchScene {
  kind: PitchSceneKind;
  /** Заголовок сцены — что получит фирма. */
  title: string;
  text: string;
  /** Короткие подписи на анимации: три метки для 'site', этапы для 'crm', узлы для 'app', рамки для 'camera'. */
  labels: readonly string[];
}

export interface Pitch {
  /** Заголовок презентации: «… для автосервиса». */
  headline: string;
  /** Одна фраза для письма: что именно сделаем этой фирме. */
  letterLine: string;
  scenes: readonly PitchScene[];
}

const site = (title: string, text: string, labels: readonly string[]): PitchScene => ({
  kind: 'site',
  title,
  text,
  labels,
});
const crm = (title: string, text: string, labels: readonly string[]): PitchScene => ({
  kind: 'crm',
  title,
  text,
  labels,
});
const app = (title: string, text: string, labels: readonly string[]): PitchScene => ({
  kind: 'app',
  title,
  text,
  labels,
});
const camera = (title: string, text: string, labels: readonly string[]): PitchScene => ({
  kind: 'camera',
  title,
  text,
  labels,
});

