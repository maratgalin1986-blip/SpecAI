export const MSK_OFFSET = 3;

/** Смещение от UTC для города фирмы; неизвестный или пустой город — Москва. */
export function cityUtcOffset(city: string | null | undefined): number {
  const known = city ? cityByName(city.trim()) : null;
  if (!known) return MSK_OFFSET;
  return REGION_OFFSET[known.region] ?? MSK_OFFSET;
}

/** Час на месте у фирмы (0–23). */
export function localHour(now: Date, city: string | null | undefined): number {
  return new Date(now.getTime() + cityUtcOffset(city) * 3_600_000).getUTCHours();
}

/** Рабочее ли сейчас время у фирмы: с `from` включительно до `to` не включая, по её часам. */
export function inLocalHours(
  now: Date,
  city: string | null | undefined,
  hours: { from: number; to: number },
): boolean {
  const hour = localHour(now, city);
  return hour >= hours.from && hour < hours.to;
}
