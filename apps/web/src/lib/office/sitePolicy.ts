// Политика обработки персональных данных посетителей клиентского сайта (К17): страница
// /s/<slug>/politika. Оператор — сама компания (название и адрес из карточки или правок
// владельца), площадка (ООО «СПЕЦПЛАСТ 16», SITE) обрабатывает заявки по её поручению.
// Чистый построитель: компания и реквизиты исполнителя на входе, разделы текста на выходе.
// Текст — шаблон до заключения юриста (docs/business/sajty-pod-klyuch.md, 9.3).

/** Срок хранения заявки после её получения, месяцев (если цель не достигнута раньше). */
export const SITE_LEAD_RETENTION_MONTHS = 12;

/** Компания — оператор данных своих посетителей. */
export interface PolicyCompany {
  name: string;
  address: string | null;
  city: string | null;
  /** Телефон как на сайте, «+7 843 212-34-56». */
  phone: string;
}

/** Исполнитель, который обрабатывает данные по поручению компании (SITE). */
export interface PolicyProcessor {
  legalName: string;
  inn: string;
  ogrn: string;
  legalAddress: string;
  email: string;
  platform: string;
}

export interface PolicySection {
  title: string;
  paragraphs: string[];
}

export interface SitePolicy {
  title: string;
  sections: PolicySection[];
}

function companyAddress(c: PolicyCompany): string {
  const address = c.address?.trim();
  const city = c.city?.trim();
  if (address && city && !address.includes(city)) return `${city}, ${address}`;
  return address || city || 'указан в карточке компании на картах';
}

export function buildSitePolicy(company: PolicyCompany, processor: PolicyProcessor): SitePolicy {
  const name = company.name.trim();
  const processorLine =
    `${processor.legalName} (ИНН ${processor.inn}, ОГРН ${processor.ogrn}, ` +
    `адрес: ${processor.legalAddress}), площадка ${processor.platform}`;
  return {
    title: `Политика обработки персональных данных посетителей сайта ${name}`,
    sections: [
      {
        title: '1. Кто обрабатывает данные',
        paragraphs: [
          `Оператор персональных данных — ${name}, адрес: ${companyAddress(company)}, телефон: ${company.phone}.`,
          `По поручению оператора заявки с этого сайта принимает и передаёт оператору ${processorLine}. ` +
            'Исполнитель обрабатывает данные только для этой цели, соблюдает их конфиденциальность ' +
            'и принимает меры защиты по статье 19 Федерального закона № 152-ФЗ «О персональных данных».',
        ],
      },
      {
        title: '2. Какие данные',
        paragraphs: [
          'Через форму «Оставить заявку» — только то, что вы сами указали: имя, телефон и комментарий к заявке (если написали).',
        ],
      },
      {
        title: '3. Зачем и на каком основании',
        paragraphs: [
          'Цель — ответить на вашу заявку: перезвонить или написать вам по ней. Для рекламы и рассылок данные не используются.',
          'Основание — ваше согласие (пункт 1 части 1 статьи 6 закона № 152-ФЗ): галочка в форме перед отправкой. Без согласия заявку отправить нельзя, позвонить можно и без неё.',
        ],
      },
      {
        title: '4. Что с данными происходит',
        paragraphs: [
          'Заявка сначала записывается в базу данных на серверах в России, затем отправляется оператору письмом на его электронную почту.',
          'Для работы сайта и отправки писем используются сервисы хостинга и почтовой рассылки, серверы которых могут находиться за пределами России (трансграничная передача).',
          'Другим лицам данные не передаются, кроме случаев, предусмотренных законом.',
        ],
      },
      {
        title: '5. Сколько хранятся',
        paragraphs: [
          `До ответа на заявку и не дольше ${SITE_LEAD_RETENTION_MONTHS} месяцев с даты её получения, ` +
            'либо до отзыва согласия — что наступит раньше. Затем данные удаляются.',
        ],
      },
      {
        title: '6. Ваши права и как отозвать согласие',
        paragraphs: [
          'Вы можете узнать, какие ваши данные обрабатываются, попросить уточнить или удалить их и отозвать согласие.',
          `Для этого позвоните оператору по телефону ${company.phone} или напишите исполнителю на ${processor.email} ` +
            `с пометкой «Отзыв согласия, сайт ${name}» и укажите телефон, с которого оставляли заявку.`,
          'После отзыва согласия обработка прекращается, а данные удаляются в течение 30 дней (часть 5 статьи 21 закона № 152-ФЗ).',
        ],
      },
    ],
  };
}
