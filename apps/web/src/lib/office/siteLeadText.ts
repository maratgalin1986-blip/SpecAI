// Тексты формы заявки на клиентском сайте (К10, К17): оператор данных посетителей — сама
// компания, площадка принимает заявки по её поручению. Импорты — только модули без зависимостей:
// файл попадает в браузер вместе с SiteLeadForm.

import { quotedName } from './quotedName';

/** Текст галочки согласия: кому (компании), какие данные и зачем — ответ на заявку. */
export function siteLeadConsentLabel(companyTitle: string): string {
  return (
    `Даю согласие компании ${quotedName(companyTitle)} на обработку моих имени, телефона и комментария, ` +
    'чтобы со мной связались по этой заявке'
  );
}
