/** Comic «swear» strings: three or more of #@%&$*! in a row. */
export const CENSOR = /[#@%&$*!]{3,}/g;

/** Splits a line into plain text and censor-symbol runs, for highlighting. */
export function splitCensored(text: string): { text: string; censored: boolean }[] {
  const out: { text: string; censored: boolean }[] = [];
  let last = 0;
  for (const match of text.matchAll(CENSOR)) {
    const at = match.index ?? 0;
    if (at > last) out.push({ text: text.slice(last, at), censored: false });
    out.push({ text: match[0], censored: true });
    last = at + match[0].length;
  }
  if (last < text.length) out.push({ text: text.slice(last), censored: false });
  return out;
}

/** A joke for the speaker that is not `avoid` (the last one told). */
export function pickJoke(speaker: BanterSpeaker, avoid?: string, random = Math.random): string {
  const pool = JOKES[speaker];
  const choices = pool.length > 1 && avoid ? pool.filter((j) => j !== avoid) : pool;
  return choices[Math.floor(random() * choices.length) % choices.length]!;
}
